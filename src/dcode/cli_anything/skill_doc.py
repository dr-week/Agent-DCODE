"""
SKILL.md Manifest Generator for CLI-Anything Harnesses.
Produces agent-discoverable SKILL.md files matching the HKUDS CLI-Hub standard.
"""

from typing import Dict, List


def generate_skill_markdown(
    app_name: str, cli_filename: str, functions: List[Dict[str, str]]
) -> str:
    """Generate a CLI-Anything SKILL.md manifest for agent discovery."""
    slug = f"cli-anything-{app_name.lower().replace('_', '-')}"
    cmds = "\n".join(
        f"- `python {cli_filename} {fn['name']} --json` — {fn.get('doc') or 'Execute ' + fn['name']}"
        for fn in functions
    )
    if not cmds:
        cmds = f"- `python {cli_filename} status --json` — Inspect module status"

    return f"""---
name: {slug}
description: Agent-native CLI-Anything harness for {app_name} with deterministic --json output.
---

# {slug}

Generated by **Agent-DCODE CLI-Anything Pipeline** (modeled after `HKUDS/CLI-Anything`).

## Agent Capabilities
- **Deterministic JSON**: Append `--json` to any subcommand for machine-readable output.
- **Self-Describing**: Run `python {cli_filename} --help` to inspect arguments at runtime.
- **Dry-Run Support**: Append `--dry-run` to preview execution safely.

## Available Commands
{cmds}
"""
